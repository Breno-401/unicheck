function makeCurriculum({ id, program, modality = null, version, sourceUrl, subjects }) {
  const uniqueSubjects = [...new Set(subjects.map((name) => name.trim()).filter(Boolean))];
  return {
    id,
    program,
    modality,
    version,
    sourceUrl,
    coverage: 'official_names_only',
    subjects: uniqueSubjects.map((name, index) => ({
      id: `${id}-${index + 1}`,
      name,
      workloadHours: null,
      sourceUrl
    }))
  };
}

